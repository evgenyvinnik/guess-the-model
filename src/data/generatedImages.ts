export interface ImageProvenance {
  /** Product or generator actually used, as reported by the generation surface. */
  generator: string;
  /** Generation surface or source URL; never an inferred model attribution. */
  source: string;
  /** ISO date or timestamp at which this output was generated. */
  generatedAt: string;
  /** Version label frozen at generation time, never a moving provider-wide default. */
  modelVersion?: {
    label: string;
    certainty: 'confirmed' | 'expected';
    /** Observation or dated evidence; an expected version is explicitly an estimate. */
    basis: string;
  };
  /** An observed family identifier when the output omits a numbered revision. */
  modelFamily?: string;
  /** Conversation or quality modes are not evidence of an image-model version. */
  mode?: string;
  /** Explains why a version was not recorded or disclosed. */
  versionNote?: string;
  /** Provider-side prompt processing observed in the generation interface. */
  promptProcessing?: string;
  /** Optional description of which output was saved, for multi-image responses. */
  output?: string;
}

export interface GeneratedImage {
  id: string;
  /** Full path relative to public/, including the actual file extension. */
  image: string;
  /** Modern Meta AI output is distinct from the historical EMU collection. */
  modelName: Exclude<ModelName, 'EMU'>;
  /** Reuse the same id and exact prompt for outputs compared across generators. */
  promptId: string;
  prompt: string;
  provenance: ImageProvenance;
  /** Keep a verified original in the catalog until its provider has enough variety for rounds. */
  playable?: boolean;
}

